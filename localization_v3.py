def build_en_to_cn():
    items = sorted(EN_TO_CN_FULL.items(), key=lambda x: -len(x[0]))
    keys = [re.escape(k) for k, _ in items]
    pattern = re.compile("|".join(keys))
    def translate(text):
        # 先整句匹配
        return pattern.sub(lambda m: EN_TO_CN_FULL[m.group(0)], text)
    return translate

