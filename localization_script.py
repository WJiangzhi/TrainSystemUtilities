def translate_wiki_content_en_to_cn(content, page_path):
    """将英文 wiki 内容翻译为简体中文
    
    策略：
    1. 保留特殊语法：embed:*, {{if-mod}}, [[TOC]], front-matter
    2. 保留 Markdown 链接和图片引用
    3. 基于术语表进行全文替换翻译
    """
    import re
    
    lines = content.split("\n")
    translated_lines = []
    
    in_code_block = False
    in_front_matter = False
    front_matter_count = 0
    
    for line in lines:
        stripped = line.strip()
        
        # 处理 front-matter (YAML header)
        if stripped == "---" and not in_code_block:
            if front_matter_count < 2:
                front_matter_count += 1
                in_front_matter = (front_matter_count == 1)
            translated_lines.append(line)
            continue
        
        if in_front_matter and front_matter_count < 2:
            # 翻译 front-matter 中的 title 等字段
            if line.startswith("title:"):
                title_val = line[len("title:"):].strip()
                translated_title = translate_sentence(title_val)
                translated_lines.append(f"title: {translated_title}")
                continue
            elif line.startswith("id:") or line.startswith("tags:"):
                translated_lines.append(line)
                continue
            else:
                translated_lines.append(line)
                continue
        
        # 代码块保护
        if stripped.startswith("```"):
            in_code_block = not in_code_block
            translated_lines.append(line)
            continue
        
        if in_code_block:
            translated_lines.append(line)
            continue
        
        # 特殊行：
        # {{if-mod ...}} / {{/if}} - 保留
        # [[TOC]] - 保留
        # embed:... 行 - 保留
        # 图片引用 ![](...) - 保留路径
        # 链接 [text](url) - 翻译 text，保留 url
        # 标题 # / ## / ### ...
        # 提示块 > [!NOTE] / > [!TIP] 等
        
        if re.match(r'\{\{if-mod.*\}\}', stripped) or stripped == "{{/if}}":
            translated_lines.append(line)
            continue
        
        if stripped == "[[TOC]]":
            translated_lines.append(line)
            continue
        
        if stripped.startswith("```embed:"):
            translated_lines.append(line)
            continue
        
        if stripped.startswith("embed:"):
            translated_lines.append(line)
            continue
        
        if stripped.startswith("> [!NOTE]"):
            translated_lines.append("> [!NOTE]")
            continue
        
        if stripped.startswith("> [!TIP]"):
            translated_lines.append("> [!TIP]")
            continue
        
        if stripped.startswith("> [!WARNING]"):
            translated_lines.append("> [!WARNING]")
            continue
        
        if stripped.startswith("> [!IMPORTANT]"):
            translated_lines.append("> [!IMPORTANT]")
            continue
        
        if stripped.startswith("> ") and not re.match(r'> \[!', stripped):
            # 提示块正文
            indent = line[:len(line) - len(line.lstrip())]
            inner = line.lstrip()[2:] if line.lstrip().startswith("> ") else line.lstrip()
            translated_lines.append(indent + "> " + translate_sentence(inner))
            continue
        
        # 图片引用行 ![xxx](bws:...) - 保留，翻译alt
        img_match = re.match(r'^(\s*)!\[([^\]]*)\]\(([^)]+)\)\s*$', line)
        if img_match:
            indent, alt, url = img_match.groups()
            if url.startswith("bws:") or url.startswith("http"):
                translated_lines.append(f"{indent}![{translate_sentence(alt)}]({url})")
            else:
                translated_lines.append(f"{indent}![{translate_sentence(alt)}]({url})")
            continue
        
        # 链接行 [text](url) 可能是列表项
        # 先保留图片，再处理文本中的链接
        
        # 翻译整行，但保护 Markdown 链接 URL 和图片 URL
        translated_line = translate_line_with_links(line)
        translated_lines.append(translated_line)
    
    return "\n".join(translated_lines)

def translate_line_with_links(line):
    """翻译一行，保护链接的 URL 部分"""
    import re
    
    # 找到所有 markdown 链接 [text](url) 和图片 ![alt](url)
    # 提取 URL，用占位符替换，翻译剩余文字，再恢复 URL
    
    placeholders = []
    counter = [0]
    
    def replace_link(match):
        prefix = match.group(1) if match.group(1) else ""
        text = match.group(2)
        url = match.group(3)
        placeholder = f"__PH{counter[0]}__"
        counter[0] += 1
        placeholders.append((placeholder, prefix, text, url, False))
        return f"{prefix}[{placeholder}](__URL{counter[0]-1}__)"
    
    def replace_img(match):
        alt = match.group(1)
        url = match.group(2)
        placeholder = f"__PH{counter[0]}__"
        counter[0] += 1
        placeholders.append((placeholder, "!", alt, url, True))
        return f"![{placeholder}](__URL{counter[0]-1}__)"
    
    # 先替换图片，再替换链接
    processed = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', replace_img, line)
    processed = re.sub(r'()\[([^\]]+)\]\(([^)]+)\)', replace_link, processed)
    
    # 翻译正文
    translated = translate_sentence(processed)
    
    # 恢复 URL 和翻译链接文字
    for i, (ph, prefix, text, url, is_img) in enumerate(placeholders):
        url_marker = f"__URL{i}__"
        # 翻译 text/alt
        translated_text = translate_sentence(text)
        if is_img:
            replacement = f"![{translated_text}]({url})"
        else:
            replacement = f"{prefix}[{translated_text}]({url})"
        translated = translated.replace(f"[{ph}]({url_marker})", replacement)
        # 兼容翻译后 placeholder 的变体
        translated = translated.replace(ph, translated_text)
    
    return translated

