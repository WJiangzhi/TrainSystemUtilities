def build_conv(map_dict):
    # 从大到小匹配（词级优先于字级）
    items = sorted(map_dict.items(), key=lambda x: -len(x[0]))
    keys = [re.escape(k) for k, _ in items]
    pattern = re.compile("|".join(keys))
    def conv(text):
        return pattern.sub(lambda m: map_dict[m.group(0)], text)
    return conv

# HK 转换：先 TW 再 HK 词替换
def build_hk_conv(s2tw, hk_variant):
    tw_conv = build_conv(s2tw)
    items = sorted(hk_variant.items(), key=lambda x: -len(x[0]))
    keys = [re.escape(k) for k, _ in items]
    pattern = re.compile("|".join(keys)) if keys else None
    def conv(text):
        t = tw_conv(text)
        if pattern:
            t = pattern.sub(lambda m: hk_variant[m.group(0)], t)
        return t
    return conv

