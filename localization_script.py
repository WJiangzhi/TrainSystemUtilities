def process_lang_files():
    """生成 zh_tw.json 和 zh_hk.json"""
    base_path = "/workspace/src/main/resources/assets/trainsystemutilities/lang"
    cn_path = os.path.join(base_path, "zh_cn.json")
    
    with open(cn_path, "r", encoding="utf-8") as f:
        cn_data = json.load(f)
    
    # 生成 zh_tw.json
    tw_data = {}
    for key, value in cn_data.items():
        if isinstance(value, str):
            tw_data[key] = s2tw(value)
        else:
            tw_data[key] = value
    
    tw_path = os.path.join(base_path, "zh_tw.json")
    with open(tw_path, "w", encoding="utf-8") as f:
        json.dump(tw_data, f, ensure_ascii=False, indent=2)
    print(f"✅ 已生成: {tw_path}")
    
    # 生成 zh_hk.json
    hk_data = {}
    for key, value in cn_data.items():
        if isinstance(value, str):
            hk_data[key] = s2hk(value)
        else:
            hk_data[key] = value
    
    hk_path = os.path.join(base_path, "zh_hk.json")
    with open(hk_path, "w", encoding="utf-8") as f:
        json.dump(hk_data, f, ensure_ascii=False, indent=2)
    print(f"✅ 已生成: {hk_path}")
    
    return len(cn_data)

