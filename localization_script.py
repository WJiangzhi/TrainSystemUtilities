def s2t(text):
    """简体转繁体（基础字级转换）"""
    if not text:
        return text
    result = []
    for ch in text:
        if ch in S2T_MAP:
            result.append(S2T_MAP[ch])
        else:
            result.append(ch)
    return "".join(result)

def s2tw(text):
    """简体转台湾繁体"""
    return s2t(text)

def s2hk(text):
    """简体转香港繁体（附加HK特有词汇）"""
    result = s2t(text)
    # 替换HK特有差异词
    for simp, hk in sorted(HK_SPECIFIC.items(), key=lambda x: -len(x[0])):
        result = result.replace(s2t(simp), hk)
    return result

