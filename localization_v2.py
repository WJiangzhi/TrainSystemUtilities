def translate_line_to_cn(line):
    """翻译一行英文为中文（保留结构）"""
    stripped = line.strip()
    
    # 空行
    if not stripped:
        return line
    
    # 先整行小写匹配（长匹配优先）
    lower = stripped.lower()
    # 尝试整行匹配（去标点后）
    clean = re.sub(r'[.。,，:：;；!！?？"\'()（）\[\]【】]+$', '', lower).strip()
    
    for eng_key in sorted(EN_TO_CN.keys(), key=lambda x: -len(x)):
        if eng_key == clean or eng_key == lower:
            orig_eng, cn = EN_TO_CN[eng_key]
            # 保留前导空格
            indent = line[:len(line) - len(line.lstrip())]
            return indent + cn
    
    # 再做段落内替换：按顺序用所有词典条目替换
    result = stripped
    replaced = set()
    
    for eng_key in sorted(EN_TO_CN.keys(), key=lambda x: -len(x)):
        if eng_key in replaced:
            continue
        orig_eng, cn = EN_TO_CN[eng_key]
        # 查找英文原文（不区分大小写）并替换
        pattern = re.compile(r'\b' + re.escape(orig_eng) + r'\b', re.IGNORECASE)
        if pattern.search(result):
            result = pattern.sub(cn, result)
            replaced.add(eng_key)
    
    # 剩余英文词（长度>=4的）清理：如果有未翻译的长单词，尽量保留或附加常用译法
    # 保留缩进
    indent = line[:len(line) - len(line.lstrip())]
    return indent + result


def translate_wiki_file(en_content, ja_content=None):
    """翻译整个 wiki 文件"""
    lines = en_content.split("\n")
    result_lines = []
    
    in_code_block = False
    in_front_matter = False
    front_count = 0
    
    for line in lines:
        stripped = line.strip()
        
        # === Front Matter (YAML) ===
        if stripped == "---" and not in_code_block:
            if front_count < 2:
                front_count += 1
                in_front_matter = (front_count == 1)
            result_lines.append(line)
            continue
        
        if in_front_matter:
            if line.startswith("title:"):
                title_val = line[len("title:"):].strip()
                translated = translate_line_to_cn(title_val)
                result_lines.append(f"title: {translated.strip()}")
                continue
            elif line.startswith("id:") or line.startswith("tags:"):
                result_lines.append(line)
                continue
            else:
                result_lines.append(line)
                continue
        
        # === 代码块 ===
        if stripped.startswith("```"):
            in_code_block = not in_code_block
            result_lines.append(line)
            continue
        if in_code_block:
            result_lines.append(line)
            continue
        
        # === 特殊语法直接保留 ===
        if stripped == "[[TOC]]":
            result_lines.append(line)
            continue
        if re.match(r'\{\{if-mod.*\}\}', stripped) or stripped == "{{/if}}":
            result_lines.append(line)
            continue
        if stripped.startswith("```embed:"):
            result_lines.append(line)
            continue
        if stripped.startswith("embed:"):
            result_lines.append(line)
            continue
        if re.match(r'>\s*\[![A-Z]+\]', stripped):
            # Callout 标题保留：> [!NOTE]
            result_lines.append(line)
            continue
        
        # === Callout 正文行 (> ...) ===
        callout_match = re.match(r'^(\s*)>\s?(.*)$', line)
        if callout_match and not re.match(r'>\s*\[!', line):
            indent, content = callout_match.groups()
            translated_content = translate_line_with_links(content)
            translated_content = translate_line_to_cn(translated_content)
            result_lines.append(f"{indent}> {translated_content}")
            continue
        
        # === Markdown 标题 ===
        heading_match = re.match(r'^(#{1,6}\s+)(.*)$', line)
        if heading_match:
            prefix, title_text = heading_match.groups()
            translated = translate_line_with_links(title_text)
            translated = translate_line_to_cn(translated)
            result_lines.append(f"{prefix}{translated}")
            continue
        
        # === 列表项 ===
        list_match = re.match(r'^(\s*)([-*+]|\d+\.)(\s+)(.*)$', line)
        if list_match:
            indent, marker, space, content = list_match.groups()
            translated = translate_line_with_links(content)
            translated = translate_line_to_cn(translated)
            result_lines.append(f"{indent}{marker}{space}{translated}")
            continue
        
        # === 普通段落（含表格分隔符等）===
        # 表格分隔线 |---|---|
        if re.match(r'^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$', line):
            result_lines.append(line)
            continue
        
        # 表格行
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = stripped[1:-1].split("|")
            translated_cells = []
            for cell in cells:
                cell = cell.strip()
                t_cell = translate_line_with_links(cell)
                t_cell = translate_line_to_cn(t_cell)
                translated_cells.append(f" {t_cell} ")
            result_lines.append("|" + "|".join(translated_cells) + "|")
            continue
        
        # === 水平分割线 ===
        if re.match(r'^\s*(-{3,}|\*{3,}|_{3,})\s*$', stripped):
            result_lines.append(line)
            continue
        
        # === 普通文本行 ===
        translated = translate_line_with_links(line)
        translated = translate_line_to_cn(translated)
        result_lines.append(translated)
    
    return "\n".join(result_lines)


def translate_line_with_links(line):
    """翻译一行，保护 Markdown 链接/图片的 URL 部分"""
    import re
    
    # 先处理图片 ![alt](url)
    def img_sub(m):
        alt = m.group(1)
        url = m.group(2)
        t_alt = translate_line_to_cn(alt)
        return f"![{t_alt}]({url})"
    
    result = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', img_sub, line)
    
    # 再处理链接 [text](url) — 注意不能再匹配图片，所以前面加 (?<!\!)
    def link_sub(m):
        text = m.group(1)
        url = m.group(2)
        t_text = translate_line_to_cn(text)
        return f"[{t_text}]({url})"
    
    result = re.sub(r'(?<!\!)\[([^\]]+)\]\(([^)]+)\)', link_sub, result)
    
    return result


def s2t_markdown(content, converter):
    """Markdown 友好的简繁转换（简化可靠版）"""
    import re
    lines = content.split("\n")
    out = []
    in_code = False
    in_front = False
    fcount = 0
    
    for line in lines:
        s = line.strip()
        
        if s == "---" and not in_code:
            if fcount < 2:
                fcount += 1
                in_front = (fcount == 1)
            out.append(line)
            continue
        
        if in_front:
            if line.startswith("title:"):
                v = line[len("title:"):].strip()
                out.append("title: " + converter(v))
            else:
                out.append(line)
            continue
        
        if s.startswith("```"):
            in_code = not in_code
            out.append(line)
            continue
        if in_code:
            out.append(line)
            continue
        
        if s == "[[TOC]]" or re.match(r'\{\{if-mod', s) or s == "{{/if}}" or s.startswith("```embed:") or s.startswith("embed:"):
            out.append(line)
            continue
        if re.match(r'>\s*\[!', s):
            out.append(line)
            continue
        
        # === 保护图片和链接 ===
        protect_bucket = []
        
        def protect(match, full_text):
            idx = len(protect_bucket)
            protect_bucket.append(match)
            return f"__PROT{idx}__"
        
        # 图片：![alt](url)  先存
        def save_img(m):
            alt = m.group(1)
            url = m.group(2)
            protect_bucket.append(("img", alt, url))
            return f"__PROT{len(protect_bucket)-1}__"
        
        line_protected = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', save_img, line)
        
        def save_link(m):
            text = m.group(1)
            url = m.group(2)
            protect_bucket.append(("link", text, url))
            return f"__PROT{len(protect_bucket)-1}__"
        
        line_protected = re.sub(r'(?<!\!)\[([^\]]*)\]\(([^)]+)\)', save_link, line_protected)
        
        # 保护内联代码
        def save_code(m):
            protect_bucket.append(("code", m.group(1)))
            return f"__PROT{len(protect_bucket)-1}__"
        
        line_protected = re.sub(r'`([^`]+)`', save_code, line_protected)
        
        # 简繁转换
        converted_line = converter(line_protected)
        
        # 恢复保护项（简繁转换不会改变 __PROT 数字）
        for i, item in enumerate(protect_bucket):
            tag = f"__PROT{i}__"
            if item[0] == "img":
                _, alt, url = item
                converted_line = converted_line.replace(tag, f"![{converter(alt)}]({url})")
            elif item[0] == "link":
                _, text, url = item
                converted_line = converted_line.replace(tag, f"[{converter(text)}]({url})")
            elif item[0] == "code":
                _, code = item
                converted_line = converted_line.replace(tag, f"`{code}`")
        
        out.append(converted_line)
    
    return "\n".join(out)


