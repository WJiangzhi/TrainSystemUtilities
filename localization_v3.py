def translate_wiki_to_cn(en_content):
    """将 en_us 内容翻译为 zh_cn，正确保留链接/语法"""
    lines = en_content.split("\n")
    out = []
    in_code = False
    in_front = False
    fcount = 0

    def process_line_text(text):
        """翻译一段普通文本，不改变任何链接占位"""
        return en_to_cn(text)

    for line in lines:
        s = line.strip()

        # Front matter
        if s == "---" and not in_code:
            if fcount < 2:
                fcount += 1
                in_front = (fcount == 1)
            out.append(line)
            continue

        if in_front:
            if line.startswith("title:"):
                v = line[len("title:"):].strip()
                out.append("title: " + en_to_cn(v))
            else:
                out.append(line)
            continue

        # 代码块
        if s.startswith("```"):
            in_code = not in_code
            out.append(line)
            continue
        if in_code:
            out.append(line)
            continue

        # 特殊语法原样保留（但会处理其中的 title）
        if s == "[[TOC]]" or s == "{{/if}}":
            out.append(line)
            continue
        if re.match(r'\{\{if-mod', s):
            out.append(line)
            continue
        if s.startswith("```embed:") or s.startswith("embed:"):
            out.append(line)
            continue
        if re.match(r'>\s*\[!', s):
            # Callout 标题部分可翻译
            m = re.match(r'(>\s*\[!)([A-Za-z0-9_\- ]+)(\])', line)
            if m:
                tag = m.group(2)
                translated = en_to_cn(tag)
                line = line[:m.start(2)] + translated + line[m.end(2):]
            out.append(line)
            continue

        # === 保护链接/图片/内联代码 ===
        protect = []

        # 1. 图片 ![alt](url)
        def save_img(m):
            idx = len(protect)
            protect.append(("img", m.group(1), m.group(2)))
            return f"__PR{idx}__"
        protected_line = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', save_img, line)

        # 2. 链接 [text](url#anchor) — 翻译 text，将 url 替换为中文 url
        def save_link(m):
            idx = len(protect)
            protect.append(("link", m.group(1), m.group(2)))
            return f"__PR{idx}__"
        protected_line = re.sub(r'(?<!\!)\[([^\]]*)\]\(([^)]+)\)', save_link, protected_line)

        # 3. 内联代码
        def save_code(m):
            idx = len(protect)
            protect.append(("code", m.group(1)))
            return f"__PR{idx}__"
        protected_line = re.sub(r'`([^`]+)`', save_code, protected_line)

        # 翻译文本部分
        translated_protected = process_line_text(protected_line)

        # 恢复保护项
        for i, item in enumerate(protect):
            tag = f"__PR{i}__"
            if item[0] == "img":
                _, alt, url = item
                translated_protected = translated_protected.replace(tag, f"![{en_to_cn(alt)}]({url})")
            elif item[0] == "link":
                _, text, url = item
                # 翻译 URL 中的页面
                cn_url = translate_url(url)
                cn_text = en_to_cn(text)
                translated_protected = translated_protected.replace(tag, f"[{cn_text}]({cn_url})")
            elif item[0] == "code":
                _, code = item
                translated_protected = translated_protected.replace(tag, f"`{code}`")

        out.append(translated_protected)

    return "\n".join(out)


def translate_url(url):
    """把 [text](path/file.md#anchor) 里的 url → 对应中文 url"""
    if url.startswith("http://") or url.startswith("https://"):
        return url
    # 分离锚点
    anchor = ""
    if "#" in url:
        url, anchor = url.split("#", 1)
        anchor = "#" + anchor
    # 查 page map
    if url in PAGE_MAP:
        url = PAGE_MAP[url][0]
    # 锚点翻译
    if anchor and anchor in ANCHOR_MAP:
        anchor = ANCHOR_MAP[anchor]
    return url + anchor


def s2t_markdown(content, converter):
    """简繁转换：保护 embeds/code/if-mod/links/code blocks"""
    lines = content.split("\n")
    out = []
    in_code = False
    in_front = False
    fcount = 0
    for line in lines:
        s = line.strip()

        if s == "---" and not in_code:
            if fcount < 2:
                fcount += 1
                in_front = (fcount == 1)
            out.append(line)
            continue

        if in_front:
            if line.startswith("title:"):
                v = line[len("title:"):].strip()
                out.append("title: " + converter(v))
            else:
                out.append(line)
            continue

        if s.startswith("```"):
            in_code = not in_code
            out.append(line)
            continue
        if in_code:
            out.append(line)
            continue

        if s == "[[TOC]]" or re.match(r'\{\{if-mod', s) or s == "{{/if}}" or s.startswith("```embed:") or s.startswith("embed:"):
            out.append(line)
            continue
        if re.match(r'>\s*\[!', s):
            out.append(line)
            continue

        protect = []

        def save_img(m):
            idx = len(protect)
            protect.append(("img", m.group(1), m.group(2)))
            return f"__PR{idx}__"
        protected = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', save_img, line)

        def save_link(m):
            idx = len(protect)
            protect.append(("link", m.group(1), m.group(2)))
            return f"__PR{idx}__"
        protected = re.sub(r'(?<!\!)\[([^\]]*)\]\(([^)]+)\)', save_link, protected)

        def save_code(m):
            idx = len(protect)
            protect.append(("code", m.group(1)))
            return f"__PR{idx}__"
        protected = re.sub(r'`([^`]+)`', save_code, protected)

        converted = converter(protected)
        for i, item in enumerate(protect):
            tag = f"__PR{i}__"
            if item[0] == "img":
                _, alt, url = item
                converted = converted.replace(tag, f"![{converter(alt)}]({url})")
            elif item[0] == "link":
                _, text, url = item
                converted = converted.replace(tag, f"[{converter(text)}]({url})")
            elif item[0] == "code":
                _, code = item
                converted = converted.replace(tag, f"`{code}`")
        out.append(converted)
    return "\n".join(out)


