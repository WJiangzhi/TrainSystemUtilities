def s2tw_markdown(content):
    """Markdown 友好的简体→台湾繁体转换（保留代码块/链接/路径）"""
    return convert_markdown(content, s2tw)

def s2hk_markdown(content):
    """Markdown 友好的简体→香港繁体转换"""
    return convert_markdown(content, s2hk)

def convert_markdown(content, converter):
    """Markdown 友好的简繁转换"""
    import re
    lines = content.split("\n")
    result = []
    in_code = False
    in_front = False
    front_count = 0
    
    for line in lines:
        stripped = line.strip()
        
        # Front-matter 处理
        if stripped == "---" and not in_code:
            if front_count < 2:
                front_count += 1
                in_front = (front_count == 1)
            result.append(line)
            continue
        
        if in_front:
            if line.startswith("title:"):
                val = line[len("title:"):].strip()
                result.append(f"title: {converter(val)}")
            else:
                result.append(line)
            continue
        
        # 代码块
        if stripped.startswith("```"):
            in_code = not in_code
            result.append(line)
            continue
        
        if in_code:
            result.append(line)
            continue
        
        # 特殊语法行：保留 embed / if-mod / TOC 等
        if re.match(r'^```embed:', stripped) or stripped.startswith("embed:"):
            result.append(line)
            continue
        if re.match(r'\{\{if-mod', stripped) or stripped == "{{/if}}":
            result.append(line)
            continue
        if stripped == "[[TOC]]":
            result.append(line)
            continue
        if re.match(r'> \[!', stripped):
            result.append(line)
            continue
        
        # 链接/图片：只翻译 text/alt 部分，保留 URL
        def process_line(line):
            # 图片 ![alt](url)
            def img_sub(m):
                alt = m.group(1)
                url = m.group(2)
                return f"![{converter(alt)}]({url})"
            line = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', img_sub, line)
            # 链接 [text](url)
            def link_sub(m):
                text = m.group(1)
                url = m.group(2)
                return f"[{converter(text)}]({url})"
            line = re.sub(r'(?<!\!)\[([^\]]+)\]\(([^)]+)\)', link_sub, line)
            return line
        
        processed = process_line(line)
        
        # 转换其余文字（保护代码内文字 `code`）
        parts = re.split(r'(`[^`]*`)', processed)
        converted_parts = []
        for part in parts:
            if part.startswith("`") and part.endswith("`"):
                converted_parts.append(part)
            else:
                converted_parts.append(converter(part))
        
        result.append("".join(converted_parts))
    
    return "\n".join(result)

